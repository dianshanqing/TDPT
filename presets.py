def preset_name(name):
    normalized=str(name).replace('\\','/').removeprefix('./')
    canonical=PRESET_ALIASES.get(normalized,normalized)
    if canonical not in MODEL_PRESETS and canonical not in SUITE_PRESETS:
        raise ValueError(f'Unknown preset: {name}; select an explicit model/suite preset or an existing external JSON')
    return canonical


def get_preset(name):
    name=preset_name(name)
    return deepcopy(MODEL_PRESETS[name] if name in MODEL_PRESETS else SUITE_PRESETS[name])


